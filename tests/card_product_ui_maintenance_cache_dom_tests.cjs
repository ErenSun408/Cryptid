const fs = require('fs');
const assert = require('node:assert/strict');
const { JSDOM } = require(require('path').resolve(process.argv[2]));
const settle = () => new Promise(resolve => setTimeout(resolve, 150));
(async () => {
  const dom = new JSDOM(fs.readFileSync('ui/card_session.html', 'utf8'), { runScripts: 'outside-only', pretendToBeVisual: true });
  const w = dom.window;
  w.TextEncoder = TextEncoder;
  try {
    w.eval(fs.readFileSync('tests/card_product_ui_navigation_mock.js', 'utf8'));
    w.eval(fs.readFileSync('ui/card_session.js', 'utf8'));
    await settle();
    const d = w.document, f = w.navigationFixture;
    const element = id => d.getElementById(id);
    const click = id => element(id).click();
    const switchTo = async id => {
      element('decoy-maintenance-container').value = String(id);
      element('decoy-maintenance-container').dispatchEvent(new w.Event('change'));
      await settle(); await settle();
    };
    const writable = () => element('decoy-maintenance-writable').textContent;
    d.querySelector('[data-section=decoy]').click();
    element('decoy-password').value = 'handover';
    click('decoy-verify-submit'); click('decoy-confirm-accept'); await settle();
    d.querySelector('[data-decoy-container="3"] .container-actions button').click();
    await settle(); await settle();
    assert.equal(writable(), '512 MiB');
    await switchTo(1);
    assert.equal(writable(), '—', 'unmounted view reused another volume cache');
    f.maintenanceSpace = '4294967296,1073741824,16777216';
    click('decoy-maintenance-end'); await settle(); await settle();
    assert.equal(writable(), '16 MiB');
    f.delayVolume = true; f.completeVolume = null;
    await switchTo(3);
    assert.equal(typeof f.completeVolume, 'function');
    assert.equal(writable(), '512 MiB', 'return did not restore this mount snapshot');
    assert.match(element('decoy-maintenance-space-detail').textContent, /上次计算结果/);
    assert.equal(element('decoy-maintenance-used').textContent, '3.0');
    f.maintenanceSpace = '4294967296,1073741824,134217728';
    f.delayVolume = false; f.completeVolume(); await settle(); await settle();
    assert.equal(writable(), '128 MiB');
    assert.doesNotMatch(element('decoy-maintenance-space-detail').textContent, /上次计算结果/);
    await switchTo(1);
    f.failMeasureMaintenance = true;
    await switchTo(3);
    assert.equal(writable(), '无法读取');
    await switchTo(1);
    f.delayVolume = true; f.completeVolume = null;
    await switchTo(3);
    assert.equal(writable(), '—', 'failed snapshot survived another view switch');
    f.failMeasureMaintenance = false; f.delayVolume = false; f.completeVolume(); await settle(); await settle();
    click('decoy-maintenance-end'); await settle(); await settle();
    d.querySelector('[data-decoy-container="3"] .container-name').click(); await settle(); await settle();
    assert.equal(writable(), '—', 'unmount retained the old snapshot');
    f.protectionById = { 1: true };
    await switchTo(1);
    assert.equal(writable(), '写入已阻止', 'cached space replaced a protection warning');
    assert.equal(element('decoy-protection-warning').hidden, false);
    console.log('PASS: per-mount cache, pending refresh, fresh replacement, failure invalidation, unmount disposal, protection precedence');
  } finally { w.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
